-- Phase 3 — Pilotage (reprise Fallora, multi-boutique)
--
--   1. Objectifs mensuels par vendeuse (gerant / proprietaire les fixent,
--      chaque vendeuse lit le sien et voit sa jauge).
--   2. Periodes de vente : « cloturer et remettre a zero » les compteurs du
--      tableau de bord SANS rien supprimer ; chaque periode passee reste
--      consultable dans le calendrier.
--   3. Tableau de bord decisionnel calcule par la base, au fuseau horaire de
--      la boutique : periode en cours, aujourd'hui / 7 jours / 14 jours,
--      mois courant vs mois precedent (a date egale), encaissements par mode,
--      top produits par CA et par benefice, benefice et marge (prix d'achat
--      de la phase 2), classement des vendeuses.
--   4. Calendrier : CA / encaisse / reste par periode, par mois, par semaine.
--
-- Toutes les fonctions : security definer + search_path = '' + controle
-- explicite de la boutique (prive.mon_organisation_id()). Rejouable.
-- ═══════════════════════════════════════════════════════════════════════

-- ─── 1. Objectifs des vendeuses ────────────────────────────────────────
create table if not exists public.objectifs_vendeuses (
  id              bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id) on delete cascade,
  vendeuse_id     bigint not null references public.utilisateurs (id) on delete cascade,
  mois            date   not null check (extract(day from mois) = 1),
  objectif        numeric not null check (objectif > 0),
  maj_par         bigint references public.utilisateurs (id) on delete set null,
  maj_le          timestamptz not null default now(),
  unique (vendeuse_id, mois)
);
create index if not exists objectifs_org_mois_idx on public.objectifs_vendeuses (organisation_id, mois);

alter table public.objectifs_vendeuses enable row level security;
revoke all on public.objectifs_vendeuses from anon, authenticated;
grant select on public.objectifs_vendeuses to authenticated;
grant all on public.objectifs_vendeuses to service_role;

drop policy if exists "objectifs: gestion lit" on public.objectifs_vendeuses;
create policy "objectifs: gestion lit" on public.objectifs_vendeuses for select to authenticated
  using (prive.est_admin() and organisation_id = prive.mon_organisation_id());
drop policy if exists "objectifs: la vendeuse lit le sien" on public.objectifs_vendeuses;
create policy "objectifs: la vendeuse lit le sien" on public.objectifs_vendeuses for select to authenticated
  using (vendeuse_id = prive.mon_utilisateur_id());

-- Fixe (ou retire, si 0 / null) l'objectif d'une vendeuse pour un mois.
create or replace function public.definir_objectif(p_vendeuse_id bigint, p_mois date, p_objectif numeric)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_org  bigint := prive.mon_organisation_id();
  v_nom  text;
  v_mois date := date_trunc('month', p_mois)::date;
begin
  if not prive.est_admin() then
    raise exception 'Reserve au gerant ou au proprietaire';
  end if;
  select nom into v_nom from public.utilisateurs
   where id = p_vendeuse_id and organisation_id = v_org and actif = true;
  if v_nom is null then
    raise exception 'Vendeuse introuvable';
  end if;
  if p_mois is null then
    raise exception 'Mois obligatoire';
  end if;
  if p_objectif is not null and (p_objectif < 0 or p_objectif > 1e12) then
    raise exception 'Objectif invalide';
  end if;

  if coalesce(p_objectif, 0) = 0 then
    delete from public.objectifs_vendeuses where vendeuse_id = p_vendeuse_id and mois = v_mois;
  else
    insert into public.objectifs_vendeuses (organisation_id, vendeuse_id, mois, objectif, maj_par, maj_le)
    values (v_org, p_vendeuse_id, v_mois, p_objectif, prive.mon_utilisateur_id(), now())
    on conflict (vendeuse_id, mois) do update
      set objectif = excluded.objectif, maj_par = excluded.maj_par, maj_le = now();
  end if;

  perform prive.journaliser('objectif_defini', 'info',
    jsonb_build_object('vendeuse', v_nom, 'mois', to_char(v_mois, 'YYYY-MM')), nullif(coalesce(p_objectif, 0), 0));
end;
$$;

-- Fuseau horaire de la boutique (reglage phase 0).
create or replace function prive.fuseau(p_org bigint)
returns text language sql stable security definer set search_path = '' as $$
  select coalesce((select fuseau_horaire from public.organisations where id = p_org), 'Africa/Douala')
$$;

-- Ventes non annulees d'un utilisateur sur un mois local [debut, debut + 1 mois).
create or replace function prive.realise_mois(p_utilisateur bigint, p_org bigint, p_mois date)
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('realise', coalesce(sum(v.total), 0), 'nb', count(*))
    from public.ventes v
   where v.organisation_id = p_org
     and v.vendeuse_id = p_utilisateur
     and v.annulee = false
     and v.date_vente >= (p_mois::timestamp at time zone prive.fuseau(p_org))
     and v.date_vente <  ((p_mois + interval '1 month')::timestamp at time zone prive.fuseau(p_org))
$$;

-- Mon objectif du mois en cours (espace vendeuse).
create or replace function public.mon_objectif()
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_moi  bigint := prive.mon_utilisateur_id();
  v_org  bigint := prive.mon_organisation_id();
  v_mois date;
begin
  if v_moi is null then
    raise exception 'Non connecte';
  end if;
  v_mois := date_trunc('month', now() at time zone prive.fuseau(v_org))::date;
  return jsonb_build_object(
    'mois', v_mois,
    'objectif', coalesce((select objectif from public.objectifs_vendeuses where vendeuse_id = v_moi and mois = v_mois), 0)
  ) || prive.realise_mois(v_moi, v_org, v_mois);
end;
$$;

-- Objectifs et realise de toute l'equipe pour un mois (page Vendeuses).
create or replace function public.objectifs_du_mois(p_mois date default null)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_org  bigint := prive.mon_organisation_id();
  v_mois date;
begin
  if not prive.est_admin() then
    raise exception 'Reserve au gerant ou au proprietaire';
  end if;
  v_mois := date_trunc('month', coalesce(p_mois::timestamp, now() at time zone prive.fuseau(v_org)))::date;
  return jsonb_build_object('mois', v_mois, 'vendeuses', coalesce((
    select jsonb_agg(x order by (x->>'realise')::numeric desc, x->>'nom')
      from (
        select jsonb_build_object('id', u.id, 'nom', u.nom, 'role', u.role,
                 'objectif', coalesce(o.objectif, 0)) || prive.realise_mois(u.id, v_org, v_mois) as x
          from public.utilisateurs u
          left join public.objectifs_vendeuses o on o.vendeuse_id = u.id and o.mois = v_mois
         where u.organisation_id = v_org
           and (   (u.actif = true and u.role = 'vendeuse')
                or o.id is not null
                or exists (select 1 from public.ventes v
                            where v.vendeuse_id = u.id and v.organisation_id = v_org and v.annulee = false
                              and v.date_vente >= (v_mois::timestamp at time zone prive.fuseau(v_org))
                              and v.date_vente <  ((v_mois + interval '1 month')::timestamp at time zone prive.fuseau(v_org))))
      ) t
  ), '[]'::jsonb));
end;
$$;


-- ─── 2. Periodes de vente ──────────────────────────────────────────────
create table if not exists public.periodes (
  id              bigint generated by default as identity primary key,
  organisation_id bigint not null references public.organisations (id) on delete cascade,
  nom             text not null default 'Période en cours' check (char_length(btrim(nom)) between 1 and 80),
  debut           timestamptz not null default now(),
  fin             timestamptz,                -- null = periode ouverte
  cloturee_par    bigint references public.utilisateurs (id) on delete set null,
  cree_le         timestamptz not null default now(),
  check (fin is null or fin >= debut)
);
-- Une seule periode ouverte par boutique.
create unique index if not exists periodes_une_ouverte on public.periodes (organisation_id) where fin is null;
create index if not exists periodes_org_debut_idx on public.periodes (organisation_id, debut desc);

alter table public.periodes enable row level security;
revoke all on public.periodes from anon, authenticated;
grant select on public.periodes to authenticated;
grant all on public.periodes to service_role;

drop policy if exists "periodes: gestion lit" on public.periodes;
create policy "periodes: gestion lit" on public.periodes for select to authenticated
  using (prive.est_admin() and organisation_id = prive.mon_organisation_id());

-- Amorce : une periode ouverte par boutique, couvrant ses ventes existantes.
insert into public.periodes (organisation_id, nom, debut)
select o.id, 'Période en cours',
       least(o.created_at, coalesce((select min(v.date_vente) from public.ventes v where v.organisation_id = o.id), o.created_at))
  from public.organisations o
 where not exists (select 1 from public.periodes p where p.organisation_id = o.id);

-- Chaque nouvelle boutique demarre avec sa periode ouverte.
create or replace function prive.ouvrir_premiere_periode()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.periodes (organisation_id, nom, debut) values (new.id, 'Période en cours', new.created_at)
  on conflict do nothing;
  return new;
end;
$$;
drop trigger if exists organisations_premiere_periode on public.organisations;
create trigger organisations_premiere_periode after insert on public.organisations
  for each row execute function prive.ouvrir_premiere_periode();

-- Debut de la periode ouverte (repli : creation de la boutique).
create or replace function prive.debut_periode(p_org bigint)
returns timestamptz language sql stable security definer set search_path = '' as $$
  select coalesce(
    (select debut from public.periodes where organisation_id = p_org and fin is null),
    (select created_at from public.organisations where id = p_org),
    '-infinity'::timestamptz)
$$;

-- Ferme la periode ouverte (avec un nom) et en ouvre une neuve.
create or replace function public.cloturer_periode(p_nom text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_org   bigint := prive.mon_organisation_id();
  v_moi   bigint := prive.mon_utilisateur_id();
  v_now   timestamptz := now();
  v_id    bigint;
  v_debut timestamptz;
  v_nom   text := nullif(btrim(coalesce(p_nom, '')), '');
  v_ca    numeric;
  v_nb    integer;
begin
  if not prive.est_admin() then
    raise exception 'Reserve au gerant ou au proprietaire';
  end if;
  if v_nom is not null and char_length(v_nom) > 80 then
    raise exception 'Nom trop long (80 caracteres maximum)';
  end if;

  -- Verrou : deux clotures simultanees ne creent pas deux periodes ouvertes.
  select id, debut into v_id, v_debut from public.periodes
   where organisation_id = v_org and fin is null for update;

  if v_id is null then
    v_debut := prive.debut_periode(v_org);
    insert into public.periodes (organisation_id, nom, debut, fin, cloturee_par)
    values (v_org, coalesce(v_nom, 'Période'), v_debut, v_now, v_moi) returning id into v_id;
  else
    update public.periodes
       set fin = v_now, cloturee_par = v_moi,
           nom = coalesce(v_nom, case when nom = 'Période en cours' then 'Période' else nom end)
     where id = v_id;
  end if;

  select coalesce(sum(total), 0), count(*) into v_ca, v_nb
    from public.ventes
   where organisation_id = v_org and annulee = false and date_vente >= v_debut and date_vente < v_now;

  insert into public.periodes (organisation_id, nom, debut) values (v_org, 'Période en cours', v_now);

  perform prive.journaliser('periode_cloturee', 'attention',
    jsonb_build_object('periode', (select nom from public.periodes where id = v_id), 'ventes', v_nb, 'debut', v_debut), v_ca);

  return jsonb_build_object('periode_cloturee', v_id, 'ca', v_ca, 'nb_ventes', v_nb, 'fin', v_now);
end;
$$;

create or replace function public.renommer_periode(p_id bigint, p_nom text)
returns void language plpgsql security definer set search_path = '' as $$
declare v_nom text := btrim(coalesce(p_nom, ''));
begin
  if not prive.est_admin() then
    raise exception 'Reserve au gerant ou au proprietaire';
  end if;
  if char_length(v_nom) not between 1 and 80 then
    raise exception 'Nom obligatoire (80 caracteres maximum)';
  end if;
  update public.periodes set nom = v_nom where id = p_id and organisation_id = prive.mon_organisation_id();
  if not found then
    raise exception 'Periode introuvable';
  end if;
end;
$$;


-- ─── 3. Tableau de bord decisionnel ────────────────────────────────────
create or replace function public.tableau_de_bord_admin()
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_org       bigint := prive.mon_organisation_id();
  v_tz        text;
  v_now       timestamptz := now();
  v_local     timestamp;
  v_jour      timestamptz;   -- debut d'aujourd'hui (heure locale)
  v_mois      timestamptz;   -- debut du mois courant
  v_mois_prec timestamptz;   -- debut du mois precedent
  v_meme_date timestamptz;   -- meme moment le mois precedent
  v_depuis    timestamptz;   -- debut de la periode en cours
  v_result    jsonb;
begin
  if not prive.est_admin() then
    raise exception 'Reserve au gerant ou au proprietaire';
  end if;
  v_tz        := prive.fuseau(v_org);
  v_local     := v_now at time zone v_tz;
  v_jour      := date_trunc('day', v_local) at time zone v_tz;
  v_mois      := date_trunc('month', v_local) at time zone v_tz;
  v_mois_prec := (date_trunc('month', v_local) - interval '1 month') at time zone v_tz;
  -- 31 mars -> 28/29 fevrier : on borne au mois precedent.
  v_meme_date := least(v_local - interval '1 month', date_trunc('month', v_local) - interval '1 microsecond') at time zone v_tz;
  v_depuis    := prive.debut_periode(v_org);

  with
  ventes_org as (
    select v.* from public.ventes v where v.organisation_id = v_org and v.annulee = false
  ),
  lignes as (
    select v.date_vente, vp.produit_id, vp.quantite,
           vp.prix_unitaire * vp.quantite as ca,
           (vp.prix_unitaire - c.prix_achat_unitaire) * vp.quantite as benefice
      from ventes_org v
      join public.vente_produits vp on vp.vente_id = v.id
      left join public.vente_produits_couts c on c.vente_produit_id = vp.id
     where v.date_vente >= least(v_depuis, v_mois_prec)
  )
  select jsonb_build_object(
    'fuseau', v_tz,
    'periode', (select jsonb_build_object('id', p.id, 'nom', p.nom, 'debut', p.debut)
                  from public.periodes p where p.organisation_id = v_org and p.fin is null),
    'stats', (select jsonb_build_object(
        'total_ventes', coalesce(sum(total) filter (where date_vente >= v_depuis), 0),
        'nb_ventes', count(*) filter (where date_vente >= v_depuis),
        'encaisse', coalesce(sum(montant_paye) filter (where date_vente >= v_depuis), 0),
        'nb_payees', count(*) filter (where date_vente >= v_depuis and statut_paiement = 'paye'),
        'nb_partielles', count(*) filter (where date_vente >= v_depuis and statut_paiement <> 'paye'),
        -- Les dettes restent dues apres une cloture : toujours globales.
        'paiements_en_attente', coalesce(sum(reste_a_payer), 0),
        'nb_a_encaisser', count(*) filter (where reste_a_payer > 0),
        'ca_jour', coalesce(sum(total) filter (where date_vente >= v_jour), 0),
        'nb_jour', count(*) filter (where date_vente >= v_jour),
        'ca_7j', coalesce(sum(total) filter (where date_vente >= v_jour - interval '6 days'), 0)
      ) from ventes_org),
    'produits_vendus', coalesce((select sum(quantite) from lignes where date_vente >= v_depuis), 0),
    'comparatif', (select jsonb_build_object(
        'ca_mois', coalesce(sum(total) filter (where date_vente >= v_mois), 0),
        'nb_mois', count(*) filter (where date_vente >= v_mois),
        'ca_mois_prec', coalesce(sum(total) filter (where date_vente >= v_mois_prec and date_vente < v_mois), 0),
        'nb_mois_prec', count(*) filter (where date_vente >= v_mois_prec and date_vente < v_mois),
        'ca_mois_prec_meme_date', coalesce(sum(total) filter (where date_vente >= v_mois_prec and date_vente <= v_meme_date), 0),
        'nb_mois_prec_meme_date', count(*) filter (where date_vente >= v_mois_prec and date_vente <= v_meme_date)
      ) from ventes_org where date_vente >= v_mois_prec),
    -- 14 derniers jours, jour local par jour local (jours sans vente inclus).
    'jours', (select jsonb_agg(jsonb_build_object('jour', to_char(j.d, 'YYYY-MM-DD'), 'ca', coalesce(s.ca, 0), 'nb', coalesce(s.nb, 0)) order by j.d)
                from generate_series(date_trunc('day', v_local) - interval '13 days', date_trunc('day', v_local), interval '1 day') j(d)
                left join (select date_trunc('day', date_vente at time zone v_tz) d, sum(total) ca, count(*) nb
                             from ventes_org where date_vente >= v_jour - interval '14 days' group by 1) s on s.d = j.d),
    'ca_par_mode', coalesce((
      select jsonb_agg(m order by m.total desc) from (
        select coalesce(nullif(btrim(p.mode), ''), 'cash') as mode, sum(p.montant) as total
          from public.paiements p join ventes_org v on v.id = p.vente_id
         where v.date_vente >= v_depuis
         group by 1 having sum(p.montant) > 0
      ) m), '[]'::jsonb),
    'produits_ca', coalesce((
      select jsonb_agg(x order by x.ca desc) from (
        select coalesce(pr.nom, 'Produit supprimé') as nom, sum(l.quantite) as quantite, sum(l.ca) as ca
          from lignes l left join public.produits pr on pr.id = l.produit_id
         where l.date_vente >= v_depuis
         group by l.produit_id, pr.nom order by sum(l.ca) desc limit 5
      ) x), '[]'::jsonb),
    'produits_quantite', coalesce((
      select jsonb_agg(x order by x.quantite desc) from (
        select coalesce(pr.nom, 'Produit supprimé') as nom, sum(l.quantite) as quantite, sum(l.ca) as ca
          from lignes l left join public.produits pr on pr.id = l.produit_id
         where l.date_vente >= v_depuis
         group by l.produit_id, pr.nom order by sum(l.quantite) desc limit 5
      ) x), '[]'::jsonb),
    -- Benefice = (prix de vente - prix d'achat fige) x quantite, sur les seules
    -- lignes dont le cout est connu ; ca_couvert dit quelle part du CA compte.
    'marge', (select jsonb_build_object(
        'benefice_periode', coalesce(sum(benefice) filter (where date_vente >= v_depuis), 0),
        'ca_couvert_periode', coalesce(sum(ca) filter (where date_vente >= v_depuis and benefice is not null), 0),
        'ca_lignes_periode', coalesce(sum(ca) filter (where date_vente >= v_depuis), 0),
        'benefice_mois', coalesce(sum(benefice) filter (where date_vente >= v_mois), 0),
        'ca_couvert_mois', coalesce(sum(ca) filter (where date_vente >= v_mois and benefice is not null), 0),
        'benefice_mois_prec', coalesce(sum(benefice) filter (where date_vente >= v_mois_prec and date_vente < v_mois), 0),
        'benefice_mois_prec_meme_date', coalesce(sum(benefice) filter (where date_vente >= v_mois_prec and date_vente <= v_meme_date), 0)
      ) from lignes),
    'produits_marge', coalesce((
      select jsonb_agg(x order by x.benefice desc) from (
        select coalesce(pr.nom, 'Produit supprimé') as nom, sum(l.quantite) as quantite, sum(l.ca) as ca, sum(l.benefice) as benefice
          from lignes l left join public.produits pr on pr.id = l.produit_id
         where l.date_vente >= v_depuis and l.benefice is not null
         group by l.produit_id, pr.nom order by sum(l.benefice) desc limit 5
      ) x), '[]'::jsonb),
    'ventes_recentes', coalesce((
      select jsonb_agg(r order by r.date_vente desc) from (
        select v.id, v.date_vente, coalesce(c.nom, 'Client de passage') as cliente_nom,
               coalesce(u.nom, '—') as vendeuse_nom, v.total, v.statut_paiement
          from ventes_org v
          left join public.clientes c on c.id = v.cliente_id
          left join public.utilisateurs u on u.id = v.vendeuse_id
         order by v.date_vente desc limit 5
      ) r), '[]'::jsonb),
    'top_vendeuses', coalesce((
      select jsonb_agg(t order by t.total desc) from (
        select u.id, u.nom, count(v.id) as nb, coalesce(sum(v.total), 0) as total
          from ventes_org v join public.utilisateurs u on u.id = v.vendeuse_id
         where v.date_vente >= v_depuis
         group by u.id, u.nom order by total desc limit 3
      ) t), '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$$;


-- ─── 4. Calendrier ─────────────────────────────────────────────────────
-- p_vue : 'periode' | 'mois' | 'semaine'. Chaque groupe donne ses bornes
-- [debut, fin) pour que l'ecran charge le detail des ventes a la demande.
create or replace function public.calendrier_ventes(p_vue text)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_org bigint := prive.mon_organisation_id();
  v_tz  text;
  v_res jsonb;
begin
  if not prive.est_admin() then
    raise exception 'Reserve au gerant ou au proprietaire';
  end if;
  v_tz := prive.fuseau(v_org);

  if p_vue = 'periode' then
    select coalesce(jsonb_agg(g order by g.debut desc), '[]'::jsonb) into v_res from (
      select p.id, p.nom, p.debut, p.fin, (p.fin is null) as active,
             count(v.id) as nb, coalesce(sum(v.total), 0) as ca,
             coalesce(sum(v.montant_paye), 0) as encaisse, coalesce(sum(v.reste_a_payer), 0) as attente
        from public.periodes p
        left join public.ventes v on v.organisation_id = v_org and v.annulee = false
              and v.date_vente >= p.debut and (p.fin is null or v.date_vente < p.fin)
       where p.organisation_id = v_org
       group by p.id
    ) g;
  elsif p_vue in ('mois', 'semaine') then
    select coalesce(jsonb_agg(g order by g.debut desc), '[]'::jsonb) into v_res from (
      select to_char(b.d, 'YYYY-MM-DD') as cle,
             b.d at time zone v_tz as debut,
             (b.d + case when p_vue = 'mois' then interval '1 month' else interval '7 days' end) at time zone v_tz as fin,
             count(*) as nb, sum(total) as ca, sum(montant_paye) as encaisse, sum(reste_a_payer) as attente
        from (select date_trunc(case when p_vue = 'mois' then 'month' else 'week' end, v.date_vente at time zone v_tz) d,
                     v.total, v.montant_paye, v.reste_a_payer
                from public.ventes v where v.organisation_id = v_org and v.annulee = false) b
       group by b.d
    ) g;
  else
    raise exception 'Vue inconnue';
  end if;
  return v_res;
end;
$$;


